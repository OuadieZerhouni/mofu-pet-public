        stale = [k for k in table if k not in keys]
        if missing or stale:
            print(f"{lang}: missing {missing} stale {stale}")
            bad = True
            continue
        out = {"@@locale": lang}
        out.update({k: table[k] for k in keys})
        (L10N / f"app_{lang}.arb").write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
